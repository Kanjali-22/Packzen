/**
 * Dieline Export Utilities
 * Handles SVG, PDF, PNG, and JSON export functionality
 */

import { generateDielineLayout } from './dielineGeometry';

/**
 * Export dieline as SVG
 */
export function exportToSVG(layout, dimensions, styleId, options = {}) {
  const {
    showDimensions = true,
    showFoldLines = true,
    showCutLines = true,
    showGrid = false,
    unit = 'mm',
    scale = 1,
    margin = 20
  } = options;

  if (!layout) return null;

  const { panels, foldLines, cutLines } = layout;
  const totalWidth = layout.totalWidth + margin * 2;
  const totalHeight = layout.totalHeight + margin * 2;

  let svg = `<?xml version="1.0" encoding="UTF-8"?>\n`;
  svg += `<svg xmlns="http://www.w3.org/2000/svg" width="${totalWidth}" height="${totalHeight}" viewBox="0 0 ${totalWidth} ${totalHeight}">\n`;
  svg += `  <title>Dieline - ${styleId}</title>\n`;
  svg += `  <desc>Generated by Packzen Dieline Studio</desc>\n`;
  svg += `  <rect x="0" y="0" width="${totalWidth}" height="${totalHeight}" fill="white"/>\n`;
  
  // Definitions for line styles
  svg += `  <defs>\n`;
  svg += `    <style>\n`;
  svg += `      .cut-line { stroke: #e53e3e; stroke-width: 1.5; fill: none; }\n`;
  svg += `      .fold-line { stroke: #3182ce; stroke-width: 1; stroke-dasharray: 8,4; fill: none; }\n`;
  svg += `      .perf-line { stroke: #d69e2e; stroke-width: 1; stroke-dasharray: 4,8; fill: none; }\n`;
  svg += `      .dimension-line { stroke: #718096; stroke-width: 0.5; fill: none; marker-end: url(#arrowhead); }\n`;
  svg += `      .grid-line { stroke: #e2e8f0; stroke-width: 0.5; fill: none; }\n`;
  svg += `      .panel-fill { fill: #f7fafc; stroke: #e2e8f0; stroke-width: 0.5; }\n`;
  svg += `      .dimension-text { font-family: Arial, sans-serif; font-size: 8px; fill: #4a5568; }\n`;
  svg += `      .panel-label { font-family: Arial, sans-serif; font-size: 10px; fill: #2d3748; font-weight: bold; }\n`;
  svg += `    </style>\n`;
  svg += `    <marker id="arrowhead" markerWidth="6" markerHeight="4" refX="5" refY="2" orient="auto">\n`;
  svg += `      <path d="M0,0 L6,2 L0,4 Z" fill="#718096" />\n`;
  svg += `    </marker>\n`;
  svg += `  </defs>\n`;

  // Grid
  if (showGrid) {
    const gridSize = 10; // mm
    const cols = Math.ceil(layout.totalWidth / gridSize);
    const rows = Math.ceil(layout.totalHeight / gridSize);
    
    svg += `  <g class="grid" opacity="0.3">\n`;
    for (let i = 0; i <= cols; i++) {
      const x = margin + i * gridSize;
      svg += `    <line x1="${x}" y1="${margin}" x2="${x}" y2="${margin + layout.totalHeight}" class="grid-line"/>\n`;
    }
    for (let i = 0; i <= rows; i++) {
      const y = margin + i * gridSize;
      svg += `    <line x1="${margin}" y1="${y}" x2="${margin + layout.totalWidth}" y2="${y}" class="grid-line"/>\n`;
    }
    svg += `  </g>\n`;
  }

  // Panel fills
  svg += `  <g class="panels">\n`;
  Object.entries(layout.panels).forEach(([panelId, panel]) => {
    if (panel.type === 'glue') return;
    
    const x = margin + panel.x;
    const y = margin + panel.y;
    
    svg += `  <rect x="${x}" y="${y}" width="${panel.width}" height="${panel.height}" class="panel-fill"/>\n`;
    
    // Panel label
    svg += `  <text x="${x + panel.width / 2}" y="${y + panel.height / 2}" class="panel-label" text-anchor="middle" dominant-baseline="middle">${panelId}</text>\n`;
  });
  svg += `  </g>\n`;

  // Cut lines
  if (showCutLines) {
    svg += `  <g class="cut-lines">\n`;
    layout.cutLines.forEach(line => {
      const x = margin + line.x;
      const y = margin + line.y;
      svg += `  <rect x="${x}" y="${y}" width="${line.width}" height="${line.height}" class="cut-line"/>\n`;
    });
    svg += `  </g>\n`;
  }

  // Fold lines
  if (showFoldLines) {
    svg += `  <g class="fold-lines">\n`;
    layout.foldLines.forEach(line => {
      const x = margin + line.x;
      const y = margin + line.y;
      if (line.width > 0) {
        svg += `  <line x1="${x}" y1="${y}" x2="${x + line.width}" y2="${y}" class="fold-line"/>\n`;
      } else if (line.height > 0) {
        svg += `  <line x1="${x}" y1="${y}" x2="${x}" y2="${y + line.height}" class="fold-line"/>\n`;
      }
    });
    svg += `  </g>\n`;
  }

  // Dimension lines
  if (showDimensions) {
    svg += `  <g class="dimension-lines">\n`;
    
    // Overall dimensions
    const totalWidth_mm = layout.totalWidth;
    const totalHeight_mm = layout.totalHeight;
    
    // Width dimension (horizontal)
    svg += `  <line x1="${margin}" y1="${margin - 15}" x2="${margin + totalWidth_mm}" y2="${margin - 15}" class="dimension-line"/>\n`;
    svg += `  <line x1="${margin}" y1="${margin - 10}" x2="${margin}" y2="${margin - 20}" class="dimension-line"/>\n`;
    svg += `  <line x1="${margin + totalWidth_mm}" y1="${margin - 10}" x2="${margin + totalWidth_mm}" y2="${margin - 20}" class="dimension-line"/>\n`;
    svg += `  <text x="${margin + totalWidth_mm / 2}" y="${margin - 22}" class="dimension-text" text-anchor="middle">${totalWidth_mm.toFixed(1)} ${unit}</text>\n`;
    
    // Height dimension (vertical)
    svg += `  <line x1="${margin - 15}" y1="${margin}" x2="${margin - 15}" y2="${margin + totalHeight_mm}" class="dimension-line"/>\n`;
    svg += `  <line x1="${margin - 10}" y1="${margin}" x2="${margin - 20}" y2="${margin}" class="dimension-line"/>\n`;
    svg += `  <line x1="${margin - 10}" y1="${margin + totalHeight_mm}" x2="${margin - 20}" y2="${margin + totalHeight_mm}" class="dimension-line"/>\n`;
    svg += `  <text x="${margin - 22}" y="${margin + totalHeight_mm / 2}" class="dimension-text" text-anchor="middle" dominant-baseline="middle" transform="rotate(-90, ${margin - 22}, ${margin + totalHeight_mm / 2})">${totalHeight_mm.toFixed(1)} ${unit}</text>\n`;
    
    svg += `  </g>\n`;
  }

  svg += `</svg>\n`;
  return svg;
}

/**
 * Export dieline as JSON (project file)
 */
export function exportToJSON(layout, dimensions, styleId, materialThickness, unit, metadata = {}) {
  const project = {
    version: '1.0',
    type: 'dieline-project',
    createdAt: new Date().toISOString(),
    metadata: {
      name: metadata.name || 'Untitled Dieline',
      description: metadata.description || '',
      author: metadata.author || '',
      ...metadata
    },
    settings: {
      styleId,
      dimensions,
      materialThickness,
      unit,
      glueFlapWidth: metadata.glueFlapWidth || 0
    },
    layout: layout ? {
      panels: layout.panels,
      foldLines: layout.foldLines,
      cutLines: layout.cutLines,
      totalWidth: layout.totalWidth,
      totalHeight: layout.totalHeight
    } : null
  };

  return JSON.stringify(project, null, 2);
}

/**
 * Import dieline from JSON
 */
export function importFromJSON(jsonString) {
  try {
    const project = JSON.parse(jsonString);
    
    if (project.type !== 'dieline-project') {
      throw new Error('Invalid project file format');
    }
    
    return {
      success: true,
      project
    };
  } catch (error) {
    return {
      success: false,
      error: error.message
    };
  }
}

/**
 * Export canvas as PNG
 */
export function exportToPNG(canvas, options = {}) {
  const {
    scale = 2,
    backgroundColor = '#ffffff',
    filename = 'dieline.png'
  } = options;

  return new Promise((resolve, reject) => {
    try {
      // Create a new canvas with the desired scale
      const exportCanvas = document.createElement('canvas');
      const ctx = exportCanvas.getContext('2d');
      
      exportCanvas.width = canvas.width * scale;
      exportCanvas.height = canvas.height * scale;
      
      // Fill background
      ctx.fillStyle = backgroundColor;
      ctx.fillRect(0, 0, exportCanvas.width, exportCanvas.height);
      
      // Draw the original canvas scaled
      ctx.drawImage(canvas, 0, 0, exportCanvas.width, exportCanvas.height);
      
      // Convert to blob and download
      exportCanvas.toBlob((blob) => {
        if (blob) {
          const url = URL.createObjectURL(blob);
          const a = document.createElement('a');
          a.href = url;
          a.download = filename;
          document.body.appendChild(a);
          a.click();
          document.body.removeChild(a);
          URL.revokeObjectURL(url);
          resolve({ success: true });
        } else {
          reject(new Error('Failed to create PNG blob'));
        }
      }, 'image/png');
    } catch (error) {
      reject(error);
    }
  });
}

/**
 * Export as PDF using browser print
 */
export function exportToPDF(layout, dimensions, styleId, options = {}) {
  const {
    showDimensions = true,
    showFoldLines = true,
    showCutLines = true,
    unit = 'mm',
    pageSize = 'A4',
    orientation = 'portrait',
    margins = 20
  } = options;

  // Create a print-optimized SVG
  const svg = exportToSVG(layout, dimensions, styleId, {
    showDimensions,
    showFoldLines,
    showCutLines,
    unit,
    margin: margins
  });

  // Create a print window
  const printWindow = window.open('', '_blank');
  printWindow.document.write(`
    <!DOCTYPE html>
    <html>
    <head>
      <title>Dieline - ${styleId}</title>
      <style>
        @page {
          size: ${pageSize} ${orientation};
          margin: ${margins}mm;
        }
        body { margin: 0; padding: 0; }
        svg { width: 100%; height: auto; max-width: 100%; }
        @media print {
          body { margin: 0; }
        }
      </style>
    </head>
    <body>
      ${svg}
    </body>
    </html>
  `);
  printWindow.document.close();
  
  // Wait for SVG to load then print
  printWindow.onload = () => {
    setTimeout(() => {
      printWindow.print();
    }, 500);
  };

  return { success: true };
}

/**
 * Download file helper
 */
export function downloadFile(content, filename, mimeType) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Export project as JSON file
 */
export function exportProjectFile(projectData, filename = 'dieline-project.json') {
  const json = exportToJSON(
    projectData.layout,
    projectData.dimensions,
    projectData.styleId,
    projectData.materialThickness,
    projectData.unit,
    projectData.metadata
  );
  downloadFile(json, filename, 'application/json');
}

/**
 * Generate a unique filename
 */
export function generateFilename(baseName, extension) {
  const timestamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
  return `${baseName}-${timestamp}.${extension}`;
}